size_t base64_decode_size(size_t input_len)
{
    return ((input_len + 3) / 4) * 3;
}

int base64_decode(const char *input, size_t input_len,
                  uint8_t *output, size_t output_size,
                  size_t *output_len)
{
    size_t max_required = base64_decode_size(input_len);
    
    if (output_size < max_required) {
        if (output_len)
            *output_len = max_required;
        return BASE64_BUFFER_SMALL;
    }
    
    if (input_len == 0) {
        if (output_len)
            *output_len = 0;
        return BASE64_OK;
    }
    
    uint8_t group[4];
    size_t group_idx = 0;
    size_t out_idx = 0;
    size_t padding = 0;
    
    size_t i;
    for (i = 0; i < input_len; i++) {
        unsigned char c = (unsigned char)input[i];
        
        if (c == '=') {
            padding++;
            continue;
        }
        
        uint8_t val = decode_table[c];
        if (val == BASE64_INVALID)
            continue;
        
        padding = 0;
        
        group[group_idx++] = val;
        
        if (group_idx == 4) {
            output[out_idx++] = (uint8_t)((group[0] << 2) | (group[1] >> 4));
            output[out_idx++] = (uint8_t)((group[1] << 4) | (group[2] >> 2));
            output[out_idx++] = (uint8_t)((group[2] << 6) | group[3]);
            group_idx = 0;
        }
    }
    
    if (group_idx > 0) {
        output[out_idx++] = (uint8_t)((group[0] << 2) | (group[1] >> 4));
        
        if (group_idx == 3) {
            output[out_idx++] = (uint8_t)((group[1] << 4) | (group[2] >> 2));
        }
    }
    
    if (output_len)
        *output_len = out_idx;
    
    return BASE64_OK;
}
