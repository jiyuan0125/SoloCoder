use std::collections::HashMap;

pub fn get_advice_for_stage(stage_name: &str) -> String {
    let advice_map: HashMap<&str, &str> = [
        ("播种期", "整地施肥，选择优质种子，做好种子消毒处理，适时播种，确保播种深度均匀。"),
        ("发芽期", "保持土壤湿润，注意温度控制，防止病虫害发生，及时观察出苗情况。"),
        ("苗期", "及时间苗、补苗，适时中耕除草，合理浇水，注意防治苗期病害。"),
        ("生长期", "适时追肥，保持土壤湿度，注意病虫害监测，及时进行植株调整。"),
        ("分枝期", "合理整枝打杈，促进分枝生长，注意防治病虫害，适当增加磷钾肥。"),
        ("开花期", "控制氮肥使用，注意保花保果，监测花粉活力，辅助授粉措施。"),
        ("结果期", "加强水肥管理，及时疏花疏果，注意防治果实病虫害，适当增施钾肥。"),
        ("膨大期", "保持充足水分供应，合理追肥，注意预防裂果，及时防治病虫害。"),
        ("成熟期", "控制浇水，适时采收，注意贮藏条件，做好采收后处理工作。"),
        ("收获期", "选择适宜天气采收，分类包装，及时入库或上市销售。"),
    ].iter().cloned().collect();

    advice_map.get(stage_name)
        .copied()
        .unwrap_or("根据作物生长阶段进行常规管理，注意观察长势，及时发现问题。")
        .to_string()
}

