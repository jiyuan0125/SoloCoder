def determine_emergency_level(category: int, impact_range: str) -> Tuple[int, str]:
    impact_score = {
        "单个舱室": 1,
        "多个舱室": 2,
        "全船": 3,
        "码头区域": 3,
    }.get(impact_range, 1)

    category_severity = {
        1: 3,
        2: 2,
        3: 2,
        4: 2,
        5: 2,
        6: 2,
        7: 3,
        8: 2,
        9: 1,
    }.get(category, 1)

    total_score = impact_score + category_severity

    if total_score >= 5:
        level = 1
    elif total_score >= 3:
        level = 2
    else:
        level = 3

    return level, EMERGENCY_LEVELS[level]


